"""Build the Go SDK from spec/openapi.json (Python 3 standard library only).

Writes types_gen.go (a struct for every request and response shape) and
resources_gen.go (client.Emails.Send and the other methods, named from the
x-sdk-group and x-sdk-method of each operation). Neither is edited by hand.
"""
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = json.loads((ROOT / "spec/openapi.json").read_text())
SCHEMAS = SPEC["components"]["schemas"]
METHODS = ["get", "post", "put", "patch", "delete"]
HEADER = "// Code generated by scripts/generate.py from spec/openapi.json. DO NOT EDIT.\n\npackage smtpfast\n\n"
INITIALISMS = {"id": "ID", "ids": "IDs", "url": "URL", "urls": "URLs", "api": "API", "html": "HTML", "dns": "DNS", "ip": "IP",
               "http": "HTTP", "json": "JSON", "dkim": "DKIM", "spf": "SPF", "dmarc": "DMARC", "mx": "MX", "smtp": "SMTP", "ai": "AI"}


def words(s):
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", s)
    return [w for w in re.split(r"[^A-Za-z0-9]+", s) if w]


def go_name(s):
    out = "".join(INITIALISMS.get(w.lower(), w[:1].upper() + w[1:]) for w in words(s))
    return out if out and not out[0].isdigit() else "X" + out


def lower_name(s):
    n = go_name(s)
    m = re.match(r"^[A-Z]+(?=[A-Z][a-z]|$)", n)
    if m and len(m.group(0)) > 1:
        return m.group(0).lower() + n[len(m.group(0)):]
    n = n[:1].lower() + n[1:]
    return n + "_" if n in {"type", "func", "range", "map", "default", "select", "case", "go", "chan", "var", "package", "import", "interface"} else n


def deref(s):
    while isinstance(s, dict) and "$ref" in s:
        s = SCHEMAS[s["$ref"].split("/")[-1]]
    return s


defs = {}


def merge_all_of(schema):
    merged = {"type": "object", "properties": {}, "required": [], "description": schema.get("description")}
    for part in schema["allOf"] + [schema]:
        part = deref(part)
        if "allOf" in part and part is not schema:
            part = merge_all_of(part)
        merged["properties"].update(part.get("properties", {}))
        merged["required"] += part.get("required", [])
    return merged


def object_schema(schema):
    schema = deref(schema)
    return merge_all_of(schema) if "allOf" in schema else schema


def merge_one_of(members, description):
    merged = {"type": "object", "properties": {}, "description": description}
    for member in members:
        for key, prop in member["properties"].items():
            merged["properties"].setdefault(key, prop)
    merged["required"] = [k for k in members[0].get("required", []) if all(k in m.get("required", []) for m in members)]
    return merged


def gotype(schema, hint):
    """The Go type for a schema, and whether it can be null."""
    if schema is None or schema is True or schema == {}:
        return "any", False
    if "$ref" in schema:
        name = go_name(schema["$ref"].split("/")[-1])
        target = deref(schema)
        t = target.get("type")
        if target.get("properties") or "allOf" in target:
            return name, False
        return gotype(target, name)
    for key in ("anyOf", "oneOf"):
        if key in schema:
            members = [m for m in schema[key] if m != {"type": "null"}]
            nullable = len(members) < len(schema[key])
            if len(members) == 1:
                t, n = gotype(members[0], hint)
                return t, nullable or n
            kinds = sorted({json.dumps(deref(m).get("type")) for m in members})
            if kinds == ['"array"', '"string"']:
                return "StringList", nullable
            if all(object_schema(m).get("properties") for m in members):
                # One of several objects (one contact, or a batch): one struct
                # with every member's fields; required only when all require it.
                define(hint, merge_one_of([object_schema(m) for m in members], schema.get("description")))
                return hint, nullable
            return "any", nullable
    if "allOf" in schema:
        if len(schema["allOf"]) == 1 and not schema.get("properties"):
            return gotype(schema["allOf"][0], hint)
        return gotype(merge_all_of(schema), hint)
    types = schema.get("type")
    types = types if isinstance(types, list) else [types] if types else []
    nullable = "null" in types
    types = [t for t in types if t != "null"]
    if sorted(types) == ["array", "string"]:
        return "StringList", nullable
    if len(types) > 1:
        return "any", nullable
    t = types[0] if types else ("object" if "properties" in schema else None)
    if t == "string":
        return "string", nullable
    if t == "integer":
        return "int64", nullable
    if t == "number":
        return "float64", nullable
    if t == "boolean":
        return "bool", nullable
    if t == "array":
        item, _ = gotype(schema.get("items"), hint + "Item")
        return "[]" + item, nullable
    if t == "object":
        if not schema.get("properties"):
            extra = schema.get("additionalProperties")
            value = gotype(extra, hint + "Value")[0] if isinstance(extra, dict) else "any"
            return f"map[string]{value}", nullable
        define(hint, schema)
        return hint, nullable
    return "any", nullable


def define(name, schema):
    if name in defs:
        return
    defs[name] = ""
    required = set(schema.get("required", []))
    lines = []
    used = set()
    for key, prop in schema.get("properties", {}).items():
        field = go_name(key)
        while field in used:
            field += "_"
        used.add(field)
        t, nullable = gotype(prop, name + go_name(key))
        optional = key not in required
        scalar = not (t.startswith("[]") or t.startswith("map[") or t in ("any", "StringList"))
        if optional and nullable:
            # Three states: absent, null (clears the field), or a value.
            t = f"Nullable[{t}]"
        elif scalar and (optional or nullable):
            t = "*" + t
        # omitzero, not omitempty: an empty list that is set is still sent, so a
        # PATCH can clear a list.
        tag = f'`json:"{key}{",omitzero" if optional else ""}"`'
        doc = (deref(prop).get("description") or "").splitlines()
        if doc:
            lines.append(f"\t// {field}: {doc[0][:150]}")
        lines.append(f"\t{field} {t} {tag}")
    desc = (schema.get("description") or "").splitlines()
    comment = f"// {name}: {desc[0][:150]}\n" if desc else ""
    defs[name] = f"{comment}type {name} struct {{\n" + "\n".join(lines) + "\n}\n"


for name, schema in SCHEMAS.items():
    if "allOf" in schema:
        define(go_name(name), merge_all_of(schema))
    elif schema.get("properties"):
        define(go_name(name), schema)

ops = []
for path, item in SPEC["paths"].items():
    for method in METHODS:
        op = item.get(method)
        if not op:
            continue
        if "x-sdk-group" not in op:
            raise SystemExit(f"{op['operationId']} has no x-sdk-group/x-sdk-method")
        name = go_name(op["operationId"])
        params = op.get("parameters", [])
        body = (op.get("requestBody") or {}).get("content", {}).get("application/json", {}).get("schema")
        body_type = gotype(body, name + "Params")[0] if body is not None else None
        result = "any"
        for code, res in op.get("responses", {}).items():
            if code.startswith("2"):
                s = (res.get("content") or {}).get("application/json", {}).get("schema")
                if s is not None:
                    result = gotype(s, name + "Response")[0]
                break
        query = [p for p in params if p["in"] == "query"]
        query_type = None
        if query:
            query_type = name + "Query"
            define(query_type, {"properties": {p["name"]: p.get("schema", {}) for p in query}, "required": []})
        item_type = None
        if method == "get" and any(p["name"] == "after" for p in query):
            rs = deref(next((v for k, v in op["responses"].items() if k.startswith("2")), {}).get("content", {}).get("application/json", {}).get("schema") or {})
            data = deref((rs.get("properties") or {}).get("data") or {})
            if data.get("type") == "array" and "has_more" in (rs.get("properties") or {}):
                item_type = gotype(data.get("items"), name + "Item")[0]
        ops.append(dict(group=op["x-sdk-group"], method=go_name(op["x-sdk-method"]), http=method.upper(), path=path,
                        summary=op.get("summary", op["operationId"]), path_params=re.findall(r"\{(\w+)\}", path),
                        body=body_type, query=query_type, query_params=query, result=result, item=item_type,
                        idempotent=any(p["in"] == "header" and p["name"].lower() == "idempotency-key" for p in params)))


def ptr(t):
    return t if t.startswith("[]") or t.startswith("map[") or t in ("any", "StringList") else "*" + t


tree = {"groups": {}, "ops": []}
for op in ops:
    node = tree
    for g in op["group"]:
        node = node["groups"].setdefault(g, {"groups": {}, "ops": []})
    node["ops"].append(op)

out = [HEADER + 'import (\n\t"context"\n\t"iter"\n\t"net/url"\n)\n\nvar _ = url.Values{}\nvar _ iter.Seq2[int, error]\n']


def emit(node, prefix):
    cls = "".join(go_name(p) for p in prefix) + "Service"
    fields = [f"\t{go_name(g)} *{''.join(go_name(p) for p in prefix + [g])}Service" for g in node["groups"]]
    out.append(f"// {cls} groups the {'.'.join(prefix) or 'top-level'} operations.\ntype {cls} struct {{\n\tcore *core\n" + "\n".join(fields) + "\n}\n")
    inits = "".join(f"\t\t{go_name(g)}: new{''.join(go_name(p) for p in prefix + [g])}Service(c),\n" for g in node["groups"])
    out.append(f"func new{cls}(c *core) *{cls} {{\n\treturn &{cls}{{\n\t\tcore: c,\n{inits}\t}}\n}}\n")
    for op in node["ops"]:
        args = ["ctx context.Context"] + [f"{lower_name(p)} string" for p in op["path_params"]]
        if op["body"]:
            args.append(f"params {ptr(op['body'])}")
        if op["query"]:
            args.append(f"query *{op['query']}")
        args.append("opts ...RequestOption")
        pp = ", ".join(f'"{p}": {lower_name(p)}' for p in op["path_params"])
        q = "nil"
        lines = []
        if op["query"]:
            lines.append("\tq := url.Values{}\n\tif query != nil {")
            for p in op["query_params"]:
                f = go_name(p["name"])
                t, _ = gotype(p.get("schema", {}), "")
                if t.startswith("[]") or t in ("any", "StringList") or t.startswith("map["):
                    lines.append(f'\t\tsetQuery(q, "{p["name"]}", query.{f})')
                else:
                    lines.append(f'\t\tif query.{f} != nil {{\n\t\t\tsetQuery(q, "{p["name"]}", *query.{f})\n\t\t}}')
            lines.append("\t}")
            fmt_param = next((p for p in op["query_params"] if p["name"] == "format"), None)
            if fmt_param and "json" in (fmt_param.get("schema") or {}).get("enum", []) and (fmt_param.get("schema") or {}).get("default") != "json":
                # The typed method decodes JSON, so it asks for JSON unless told otherwise.
                lines.append('\tif q.Get("format") == "" {\n\t\tq.Set("format", "json")\n\t}')
            q = "q"
        body = "params" if op["body"] else "nil"
        result = op["result"]
        decl = f"\tvar out {result}" if result.startswith("[]") or result.startswith("map[") or result == "any" else f"\tout := new({result})"
        ret = "out" if not decl.startswith("\tout :=") else "out"
        rtype = result if decl.startswith("\tvar") else "*" + result
        call = f'\terr := s.core.do(ctx, "{op["http"]}", "{op["path"]}", map[string]string{{{pp}}}, {q}, {body}, {"true" if op["idempotent"] else "false"}, {"&out" if decl.startswith(chr(9)+"var") else "out"}, opts)'
        out.append(f"// {op['method']}: {op['summary'].rstrip('.')} ({op['http']} {op['path']}).\nfunc (s *{cls}) {op['method']}({', '.join(args)}) ({rtype}, error) {{\n" + "\n".join(lines + [decl, call]) + f"\n\tif err != nil {{\n\t\treturn nil, err\n\t}}\n\treturn {ret}, nil\n}}\n")
        if op["item"]:
            pargs = ["ctx context.Context"] + [f"{lower_name(p)} string" for p in op["path_params"]] + [f"query *{op['query']}", "opts ...RequestOption"]
            fill = "\n".join(lines).replace("\tq := url.Values{}\n", "")
            out.append(
                f"// {op['method']}All iterates over every item of {op['method']}, fetching the following pages as needed.\n"
                f"func (s *{cls}) {op['method']}All({', '.join(pargs)}) iter.Seq2[{op['item']}, error] {{\n"
                f"\tq := url.Values{{}}\n{fill}\n"
                f'\treturn paginate[{op["item"]}](ctx, s.core, "{op["path"]}", map[string]string{{{pp}}}, q, opts)\n}}\n'
            )
    for g, child in node["groups"].items():
        emit(child, prefix + [g])


emit(tree, [])
(ROOT / "resources_gen.go").write_text("\n".join(out))
(ROOT / "types_gen.go").write_text(HEADER + "\n".join(defs[k] for k in sorted(defs)))
subprocess.run(["gofmt", "-w", "types_gen.go", "resources_gen.go"], cwd=ROOT, check=True)
print(f"types_gen.go: {len(defs)} types; resources_gen.go: {len(ops)} operations")
